/**
 * Mengenali jenis gambar dari isi berkasnya (angka ajaib di awal file),
 * bukan dari label `type` yang dikirim browser.
 *
 * Label dari browser mudah dipalsukan: berkas apa pun bisa diberi label
 * "image/png". Pengecekan ini memastikan yang diunggah memang benar gambar
 * sebelum dikirim ke Cloudinary.
 */
export type JenisGambar = "image/jpeg" | "image/png" | "image/webp" | "image/gif";

export function jenisGambarDariByte(b: Uint8Array): JenisGambar | null {
  // JPEG: FF D8 FF
  if (b.length >= 3 && b[0] === 0xff && b[1] === 0xd8 && b[2] === 0xff) return "image/jpeg";

  // PNG: 89 50 4E 47 0D 0A 1A 0A
  if (
    b.length >= 8 &&
    b[0] === 0x89 && b[1] === 0x50 && b[2] === 0x4e && b[3] === 0x47 &&
    b[4] === 0x0d && b[5] === 0x0a && b[6] === 0x1a && b[7] === 0x0a
  ) {
    return "image/png";
  }

  // GIF: "GIF87a" atau "GIF89a"
  if (
    b.length >= 6 &&
    b[0] === 0x47 && b[1] === 0x49 && b[2] === 0x46 && b[3] === 0x38 &&
    (b[4] === 0x37 || b[4] === 0x39) && b[5] === 0x61
  ) {
    return "image/gif";
  }

  // WebP: "RIFF" .... "WEBP"
  if (
    b.length >= 12 &&
    b[0] === 0x52 && b[1] === 0x49 && b[2] === 0x46 && b[3] === 0x46 &&
    b[8] === 0x57 && b[9] === 0x45 && b[10] === 0x42 && b[11] === 0x50
  ) {
    return "image/webp";
  }

  return null;
}
